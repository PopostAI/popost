// Bundle bundles/deck-entry.ts (the editor's compileProject / splitProject plus a thin wrapper) into one browser script
// and write it as a string module, src/deck/compile-bundle.ts, which is committed. `popost deck export|import` runs it in
// Chromium (see src/deck/engine.ts).
//
//   node bundles/build-deck.mjs            regenerate src/deck/compile-bundle.ts
//   node bundles/build-deck.mjs --check    exit 1 when the committed file is out of date with the editor source
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const here = new URL('.', import.meta.url);
const packageRoot = fileURLToPath(new URL('../', here));
const target = new URL('../src/deck/compile-bundle.ts', here);

const HEADER = `// GENERATED by bundles/build-deck.mjs from packages/canvas-editor/src/storage/compile.ts and bundles/deck-entry.ts.
// Do not edit: run \`npm run build:deck -w popost\` (tests/deck-bundle.test.ts fails while this file is out of date).
`;

/** The module text for the current sources. */
export const renderBundleModule = async () => {
  const result = await build({
    entryPoints: ['bundles/deck-entry.ts'],
    absWorkingDir: packageRoot,
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    charset: 'utf8',
    legalComments: 'none',
    logLevel: 'warning',
  });
  const code = result.outputFiles[0].text;
  return `${HEADER}export const DECK_BUNDLE = ${JSON.stringify(code)};\n`;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fresh = await renderBundleModule();
  if (process.argv.includes('--check')) {
    const committed = await readFile(target, 'utf8').catch(() => '');
    if (committed !== fresh) {
      console.error('src/deck/compile-bundle.ts is out of date with the editor source: run `npm run build:deck -w popost`.');
      process.exitCode = 1;
    }
  } else {
    await writeFile(target, fresh);
  }
}
