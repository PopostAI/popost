// Bundle the code that runs in the browser for `popost video` into one script each, and write them as string modules,
// which are committed: the shipped package has no bundler.
//   src/video/page/main.ts           -> src/video/compile/page-bundle.ts   (PAGE_BUNDLE: the page that draws any frame)
//   src/video/preview/shell/main.ts  -> src/video/preview/shell-bundle.ts  (SHELL_BUNDLE: the preview's shell)
//
//   node bundles/build-video.mjs            regenerate both files
//   node bundles/build-video.mjs --check    exit 1 when a committed file is out of date with its source
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const here = new URL('.', import.meta.url);
const packageRoot = fileURLToPath(new URL('../', here));

/** Each bundle: its entry, the constant it is exported as, and the committed file (paths from the package root). */
export const VIDEO_BUNDLES = [
  { entry: 'src/video/page/main.ts', name: 'PAGE_BUNDLE', target: 'src/video/compile/page-bundle.ts' },
  { entry: 'src/video/preview/shell/main.ts', name: 'SHELL_BUNDLE', target: 'src/video/preview/shell-bundle.ts' },
];

const header = (entry) => `// GENERATED by bundles/build-video.mjs from ${entry} and what it imports.
// Do not edit: run \`npm run build:video -w popost\` (tests/video/make-bundle.test.ts fails while this file is out of date).
`;

/** The module text of one bundle for the current sources. The options are the ones the engine used at run time before. */
export const renderVideoBundle = async ({ entry, name }) => {
  const result = await build({
    entryPoints: [entry],
    absWorkingDir: packageRoot,
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'chrome110',
    minify: true,
    legalComments: 'none',
    logLevel: 'warning',
  });
  const code = result.outputFiles[0].text;
  return `${header(entry)}export const ${name} = ${JSON.stringify(code)};\n`;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const bundle of VIDEO_BUNDLES) {
    const fresh = await renderVideoBundle(bundle);
    const target = new URL('../' + bundle.target, here);
    if (process.argv.includes('--check')) {
      const committed = await readFile(target, 'utf8').catch(() => '');
      if (committed !== fresh) {
        console.error(bundle.target + ' is out of date with ' + bundle.entry + ': run `npm run build:video -w popost`.');
        process.exitCode = 1;
      }
    } else {
      await writeFile(target, fresh);
    }
  }
}
