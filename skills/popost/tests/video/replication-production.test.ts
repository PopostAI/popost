/** Strict replication guards run before mocked paid work; all files and generators are in memory. */
import { describe, expect, it } from 'vitest';
import { sha256 } from '../../src/core/util';
import { createTestRuntime, runCli, type TestRuntime } from '../../src/testing/memory';
import { makeMaterials, type Generator, type GenerateRequest } from '../../src/video/generate/index';
import { parseReplicationContract, type ReplicationContract, type ReplicationEvidence } from '../../src/video/replication/contract';
import { checkReplicationAudio } from '../../src/video/replication/check';
import { copyReplication, readReplication } from '../../src/video/replication/io';
import { AUDIO_FILE, fillReplicationProblems, materialReplicationProblems, speechReplicationProblems, outputAudioProblems, outputPlanProblems } from '../../src/video/replication/production';
import { fillPackage } from '../../src/video/template/fill';
import { loadTemplate, saveTemplate } from '../../src/video/template/save';
import type { Measure, Problem, Resolved } from '../../src/video/types';

const sourceBytes = new TextEncoder().encode('synthetic reference bytes');
const audioBytes = new TextEncoder().encode('synthetic audio bytes');
const sourceHash = sha256(sourceBytes), audioHash = sha256(audioBytes);
const sourceEvidence = (): ReplicationEvidence => ({ kind: 'observed', detail: 'Inspected reference picture and listened to its music.', file: 'source.mp4', sha256: sourceHash, media: 'video' });
const contract = (): ReplicationContract => ({
  format: 'popost-video-replication', version: 1, source: { fingerprint: sourceHash, fps: 30, frames: 60 },
  audio: { sourceSpeech: 'absent', sourceRoles: ['music'], narration: 'preserve', evidence: [sourceEvidence()] },
  visual: { medium: 'hand-drawn', style: ['Pencil outlines and textured paper'], evidence: [sourceEvidence()] },
  inventory: { status: 'complete', evidence: [sourceEvidence()] }, events: [],
});
const bind = async (rt: TestRuntime, dir: string, c = contract()) => {
  await rt.fs.writeFile(dir + '/source.mp4', sourceBytes);
  await rt.fs.writeFile(dir + '/replication.json', JSON.stringify(c));
};
const errors = (problems: readonly Problem[]) => problems.filter(p => p.level === 'error');
const audioItem = (role: 'music' | 'narration' | 'dialogue' = 'music', speech: 'present' | 'absent' = 'absent') => ({
  file: 'assets/audio.wav', sha256: audioHash, kind: 'sound' as const, role, speech,
  evidence: [{ kind: 'observed', detail: 'Listened to this exact output audio.', file: 'assets/audio.wav', sha256: audioHash, media: 'audio' }],
});
const inventory = async (rt: TestRuntime, dir: string, role: 'music' | 'narration' | 'dialogue' = 'music', speech: 'present' | 'absent' = 'absent') => {
  await rt.fs.writeFile(dir + '/assets/audio.wav', audioBytes);
  await rt.fs.writeFile(dir + '/' + AUDIO_FILE, JSON.stringify({ version: 1, items: [audioItem(role, speech)] }));
};
const generator = (rt: TestRuntime) => {
  const sent: GenerateRequest[] = [];
  const g: Generator = { make: async (_kind, request, out) => { sent.push(request); await rt.fs.writeFile(out, 'generated bytes'); return { credits: 7 }; } };
  return { g, sent };
};
const request = () => ({ file: 'assets/shot.mp4', prompt: 'A copper sphere rolls across paper.', cast: [], seconds: 2 });
const resolved = (audio: Resolved['audio'] = []): Resolved => ({
  canvas: { width: 320, height: 180, fps: 30 }, frames: 60,
  segments: [{ id: 'shot', index: 0, start: 0, end: 60, base: { kind: 'scene', src: 'scenes/shot.html' } }], items: [], audio,
});
const measure: Measure = {
  version: 1, source: { width: 320, height: 180, fps: 30, frames: 60, duration: 2, hasAudio: false },
  boundaries: [], shots: [{ index: 0, start: 0, end: 60, camera: { kind: 'static', zoomPerS: 0, panPerS: [0, 0], confidence: 1 }, background: '#202020', palette: [{ hex: '#202020', share: 1 }], events: [] }],
  rhythm: { step: 3, change: Array(20).fill(0) as number[] }, signature: { every: 3, width: 16, height: 16, count: 0, data: '' },
};
const template = async (rt: TestRuntime) => {
  const made = await saveTemplate(rt, { measure, name: 'Synthetic', outDir: '/work/template', text: { step: 3, sampled: 20, cues: [{ text: 'Hello', start: 0, end: 60, role: 'caption', box: [0.1, 0.8, 0.8, 0.1], size: 0.05, samples: 10, confidence: 1 }] } });
  expect(errors(made.problems)).toEqual([]);
  return loadTemplate(rt, '/work/template');
};

describe('strict generation and fill preflights', () => {
  it('keeps legacy generation and fill unchanged when no replication sidecar exists', async () => {
    const rt = createTestRuntime(), { g, sent } = generator(rt);
    const made = await makeMaterials(rt, { dir: '/work/legacy', requests: [request()], generator: g, anchor: false });
    expect(made.materials[0]).toMatchObject({ made: true, credits: 7 });
    expect(sent).toHaveLength(1); expect(sent[0]?.prompt).toBe(request().prompt);
    expect(await fillReplicationProblems(rt, '/work/legacy', '/work/assets', { speak: true, sound: 'unreviewed.wav' })).toEqual([]);
    const pkg = await template(rt);
    const filled = await fillPackage(rt, pkg, { outDir: '/work/filled', fill: { shots: [{ color: '#101040' }], captions: ['Hello'] } });
    expect(errors(filled.problems)).toEqual([]); expect(filled.project).toBeDefined();
    expect(await rt.fs.stat('/work/filled/replication.json')).toBeNull();
  });
  it('blocks an unreviewed inventory before invoking a paid generator', async () => {
    const rt = createTestRuntime(), { g, sent } = generator(rt), c = contract();
    c.inventory = { status: 'unknown', evidence: [] }; await bind(rt, '/work/project', c);
    const made = await makeMaterials(rt, { dir: '/work/project', requests: [request()], generator: g });
    expect(errors(made.problems).some(p => p.at === 'replication.inventory')).toBe(true);
    expect(sent).toEqual([]); expect([made.credits, made.chargedCredits]).toEqual([0, 0]);
  });
  it('never treats a malformed sidecar as a legacy project', async () => {
    const rt = createTestRuntime({ files: { '/work/project/replication.json': '{broken' } }), { g, sent } = generator(rt);
    const made = await makeMaterials(rt, { dir: '/work/project', requests: [request()], generator: g });
    expect(errors(made.problems).length).toBeGreaterThan(0); expect(sent).toEqual([]);
  });
  it('keeps instrumental native generation allowed and adds a no-speech constraint to its actual prompt', async () => {
    const rt = createTestRuntime(), { g, sent } = generator(rt); await bind(rt, '/work/project');
    const made = await makeMaterials(rt, { dir: '/work/project', requests: [request()], generator: g, anchor: false });
    expect(errors(made.problems)).toEqual([]); expect(sent).toHaveLength(1);
    expect(sent[0]?.prompt).toContain('Do not add dialogue');
    expect(sent[0]?.prompt).toContain('music, effects and ambience');
  });
  it('blocks declared native speech before any paid generator call', async () => {
    const rt = createTestRuntime(), { g, sent } = generator(rt); await bind(rt, '/work/project');
    const made = await makeMaterials(rt, { dir: '/work/project', requests: [{ ...request(), speech: { mode: 'native', speaker: 'host', text: 'Unrequested lecture.' } }], generator: g });
    expect(errors(made.problems).some(p => p.at.startsWith('replication.audioUses'))).toBe(true); expect(sent).toEqual([]);
  });
  it('blocks strict TTS fill before the injected speaker is called', async () => {
    const rt = createTestRuntime(), pkg = await template(rt); let spoken = 0;
    const c = contract(); c.inventory = { status: 'unknown', evidence: [] }; await bind(rt, '/work/template', c);
    const filled = await fillPackage(rt, pkg, { outDir: '/work/filled', fill: { shots: [{ color: '#101040' }], captions: ['Hello'] }, speak: true, speaker: { speak: async () => { spoken++; } } });
    expect(errors(filled.problems).length).toBeGreaterThan(0); expect(spoken).toBe(0); expect(filled.project).toBeUndefined();
  });
  it('prevents external sound from bypassing narration intent while allowing actual music', async () => {
    const rt = createTestRuntime(); await bind(rt, '/work/template');
    await inventory(rt, '/work/assets', 'narration', 'present');
    expect(errors(await fillReplicationProblems(rt, '/work/template', '/work/assets', { sound: 'assets/audio.wav' })).some(p => p.at.startsWith('replication.audioUses'))).toBe(true);
    await inventory(rt, '/work/assets');
    expect(await fillReplicationProblems(rt, '/work/template', '/work/assets', { sound: 'assets/audio.wav' })).toEqual([]);
    expect(errors(await fillReplicationProblems(rt, '/work/template', '/work/assets', { beds: [{ footage: 'unclassified.mp4' }] })).length).toBeGreaterThan(0);
  });
  it('keeps a song with intelligible words and never promotes it into narrator permission', async () => {
    const rt = createTestRuntime(), c = contract(); c.audio.sourceSpeech = 'present'; c.audio.sourceRoles = ['music']; c.audio.narration = 'forbid';
    await bind(rt, '/work/template', c); await inventory(rt, '/work/assets', 'music', 'present');
    expect(await fillReplicationProblems(rt, '/work/template', '/work/assets', { sound: 'assets/audio.wav' })).toEqual([]);
    await inventory(rt, '/work/assets', 'narration', 'present');
    expect(errors(await fillReplicationProblems(rt, '/work/template', '/work/assets', { sound: 'assets/audio.wav' })).length).toBeGreaterThan(0);
    await bind(rt, '/work/project', c); const { g, sent } = generator(rt);
    const made = await makeMaterials(rt, { dir: '/work/project', requests: [request()], generator: g, anchor: false });
    expect(errors(made.problems)).toEqual([]);
    expect(sent[0]?.prompt).toContain('Do not add a voice-over or narrator');
    expect(sent[0]?.prompt).toContain('music/vocals');
    expect(sent[0]?.prompt).not.toContain('Do not add dialogue');
    expect(errors((await materialReplicationProblems(rt, '/work/project', [{ ...request(), speech: { mode: 'native', speaker: 'host', text: 'An unrequested explanation over the song.' } }])).problems).length).toBeGreaterThan(0);
  });
  it('permits a partial silent request but catches missing preserved speech in final audio', async () => {
    const rt = createTestRuntime(), c = contract(); c.audio.sourceSpeech = 'present'; c.audio.sourceRoles = ['dialogue']; await bind(rt, '/work/project', c);
    expect(errors((await materialReplicationProblems(rt, '/work/project', [request()])).problems)).toEqual([]);
    expect(errors(await outputAudioProblems(rt, '/work/project', c, resolved())).length).toBeGreaterThan(0);
    expect(checkReplicationAudio(c, [], { complete: true }).some(p => p.level === 'error')).toBe(true);
  });
});

describe('actual media evidence and portable sidecars', () => {
  it('keeps an explicit new dialogue request usable through the shared-voice route without adding a narrator', async () => {
    const rt = createTestRuntime(), c = contract();
    c.audio.narration = 'forbid';
    c.audio.userOverride = { instruction: 'Add spoken dialogue between the characters.', evidence: [{ kind: 'user', detail: 'The user explicitly requests new character dialogue.' }] };
    await bind(rt, '/work/project', c);
    expect(await speechReplicationProblems(rt, '/work/project')).toEqual([]);
    c.audio.narration = 'requested';
    c.audio.userOverride.instruction = 'Add an explanatory narrator.';
    await bind(rt, '/work/project', c);
    expect(await speechReplicationProblems(rt, '/work/project')).toEqual([]);
  });
  it('rejects changed source evidence and changed imported audio bytes', async () => {
    const rt = createTestRuntime(); await bind(rt, '/work/template'); await inventory(rt, '/work/assets');
    await rt.fs.writeFile('/work/template/source.mp4', 'changed source');
    expect(errors((await readReplication(rt, '/work/template')).problems).length).toBeGreaterThan(0);
    const { g, sent } = generator(rt);
    expect(errors((await makeMaterials(rt, { dir: '/work/template', requests: [request()], generator: g })).problems).length).toBeGreaterThan(0);
    expect(sent).toEqual([]);
    await bind(rt, '/work/template'); await rt.fs.writeFile('/work/assets/assets/audio.wav', 'changed audio');
    expect(errors(await fillReplicationProblems(rt, '/work/template', '/work/assets', { sound: 'assets/audio.wav' })).length).toBeGreaterThan(0);
  });
  it('copies every bound evidence file so a moved template stays valid after its source directory disappears', async () => {
    const rt = createTestRuntime(); await bind(rt, '/work/reference');
    expect(await copyReplication(rt, '/work/reference', '/work/template')).toEqual([]);
    await rt.fs.rm('/work/reference');
    const copied = await readReplication(rt, '/work/template');
    expect(copied.problems).toEqual([]); expect(copied.contract?.source.fingerprint).toBe(sourceHash);
    expect(copied.contract?.inventory?.evidence[0]?.file).toMatch(/^replication-evidence\//);
  });
  it('carries a strict sidecar through save and fill rather than losing the reference constraints', async () => {
    const rt = createTestRuntime(); await bind(rt, '/work/reference');
    expect(errors((await saveTemplate(rt, { measure, name: 'Strict', referenceDir: '/work/reference', outDir: '/work/template' })).problems)).toEqual([]);
    const filled = await fillPackage(rt, await loadTemplate(rt, '/work/template'), { outDir: '/work/project', fill: { shots: [{ color: '#101040' }] } });
    expect(errors(filled.problems)).toEqual([]); expect(filled.project).toBeDefined();
    await rt.fs.rm('/work/reference'); await rt.fs.rm('/work/template');
    expect((await readReplication(rt, '/work/project')).problems).toEqual([]);
  });
  it('copies the imported sound and its review to the filled project for a final audio gate', async () => {
    const rt = createTestRuntime(), pkg = await template(rt); await bind(rt, '/work/template'); await inventory(rt, '/work/assets');
    const filled = await fillPackage(rt, pkg, { outDir: '/work/project', assetsDir: '/work/assets', fill: { shots: [{ color: '#101040' }], captions: ['Hello'], sound: 'assets/audio.wav' } });
    expect(errors(filled.problems)).toEqual([]); expect(filled.project).toBeDefined();
    expect(await rt.fs.readFile('/work/project/assets/audio.wav')).toEqual(audioBytes);
    expect(await outputAudioProblems(rt, '/work/project', contract(), resolved([{ id: 'music', src: 'assets/audio.wav', start: 0, end: 60, gain: 1 }]))).toEqual([]);
  });
  it('cannot omit an actual resolved native audio route from the inventory', async () => {
    const rt = createTestRuntime(), c = contract();
    const r = resolved([{ id: 'native', src: 'assets/native.mp4', start: 0, end: 60, gain: 1 }]);
    await rt.fs.writeFile('/work/project/assets/native.mp4', 'native bytes');
    expect(errors(await outputAudioProblems(rt, '/work/project', c, r)).some(p => p.message.includes('missing from the inventory'))).toBe(true);
  });
  it('uses actual compiled segment intervals rather than merely trusting author-supplied event times', async () => {
    const rt = createTestRuntime(), c = contract();
    c.events = [{ id: 'reveal', kind: 'typing', mechanism: 'characters', objects: ['heading'], span: [0, 30], description: 'Letters arrive individually.', evidence: [sourceEvidence()] }];
    await rt.fs.writeFile('/work/project/replication.plan.json', JSON.stringify({ version: 1, visual: { ...c.visual, evidence: [] }, events: [{ id: 'reveal', segment: 'shot', span: [0, 70], method: 'deterministic typing', mechanism: 'characters', evidence: [] }] }));
    expect(errors(await outputPlanProblems(rt, '/work/project', c, resolved())).some(p => p.message.includes('outside its compiled'))).toBe(true);
  });
  it('converts source-event time to target frames and rejects drift inside an otherwise valid long segment', async () => {
    const rt = createTestRuntime(), c = contract(); c.source.fps = 24; c.source.frames = 48;
    c.events = [{ id: 'typing', kind: 'typing', mechanism: 'characters', objects: ['heading'], span: [6, 24], description: 'Letters appear between source0.25s and1s.', evidence: [sourceEvidence()] }];
    const file = '/work/project/replication.plan.json';
    const plan = { version: 1, visual: { ...c.visual, evidence: [] }, events: [{ id: 'typing', segment: 'shot', span: [8, 30], method: 'deterministic typing', mechanism: 'characters', evidence: [] }] };
    await rt.fs.writeFile(file, JSON.stringify(plan));
    expect(errors(await outputPlanProblems(rt, '/work/project', c, resolved()))).toEqual([]);
    plan.events[0]!.span = [30, 52]; await rt.fs.writeFile(file, JSON.stringify(plan));
    expect(errors(await outputPlanProblems(rt, '/work/project', c, resolved())).length).toBeGreaterThan(0);
  });
  it('preserves source finish as well as medium and rejects an unproven visual override', async () => {
    const rt = createTestRuntime(), c = contract(), file = '/work/project/replication.plan.json';
    await rt.fs.writeFile(file, JSON.stringify({ version: 1, visual: { medium: c.visual.medium, style: ['Generic flat shading'], evidence: [] }, events: [] }));
    expect(errors(await outputPlanProblems(rt, '/work/project', c, resolved())).length).toBeGreaterThan(0);
    await rt.fs.writeFile(file, JSON.stringify({ version: 1, visual: { medium: 'procedural-3D', style: c.visual.style, evidence: [], userOverride: { instruction: 'Use a different medium.', evidence: [{ kind: 'observed', detail: 'The author preferred simpler geometry.' }] } }, events: [] }));
    expect(errors(await outputPlanProblems(rt, '/work/project', c, resolved())).length).toBeGreaterThan(0);
  });
  it('reports local readiness through the real CLI and rejects incomplete facts', async () => {
    const rt = createTestRuntime(); await bind(rt, '/work/project');
    expect((await runCli(rt, ['video', 'replication', 'check', '/work/project'])).code).toBe(0);
    expect(rt.json()).toMatchObject({ ok: true, ready: true });
    const c = contract(); c.inventory = { status: 'unknown', evidence: [] }; await bind(rt, '/work/project', c);
    expect((await runCli(rt, ['video', 'replication', 'check', '/work/project'])).code).toBe(2);
    expect(rt.json()).toMatchObject({ ok: false, ready: false });
    expect(parseReplicationContract(c).contract).toBeDefined();
  });
  it('binds CLI final acceptance to actual artifact bytes and in-range sampled frame indices', async () => {
    const crc = '#tb 0: 1/30\n' + Array.from({ length: 60 }, (_, i) => `0, ${i}, ${i}, 1, 100, 0x00000000`).join('\n');
    const rt = createTestRuntime({ programs: { parallelism: 1, tempDir: async () => '/scratch', run: async () => ({ code: 0, stdout: new TextEncoder().encode(crc), stderr: 'Duration: 00:00:02.00\nStream #0:0: Video: h264, yuv420p, 320x180, 30 fps\n' }) } });
    const pkg = await template(rt), filled = await fillPackage(rt, pkg, { outDir: '/work/project', fill: { shots: [{ color: '#101040' }], captions: ['Hello'] } });
    expect(filled.project).toBeDefined();
    const c = contract(); c.audio.sourceRoles = []; c.events = [{ id: 'heading', kind: 'typing', mechanism: 'characters', objects: ['heading'], span: [0, 30], description: 'Individual letter reveal.', evidence: [sourceEvidence()] }];
    await bind(rt, '/work/project', c);
    const finalBytes = new TextEncoder().encode('synthetic final artifact'), fingerprint = sha256(finalBytes);
    await rt.fs.writeFile('/work/project/final.mp4', finalBytes);
    const frame = (n: number): ReplicationEvidence => ({ kind: 'observed', detail: 'Inspected an actual final-video sample.', file: 'final.mp4', sha256: fingerprint, media: 'video', frame: n });
    const review = { production: 'rendered', sourceFingerprint: sourceHash, artifactFingerprint: fingerprint, target: { fps: 30, frames: 60 }, audio: { status: 'passed', evidence: [{ ...frame(0), at: [0, 2] }] }, visual: { status: 'passed', evidence: [frame(0)] }, events: [{ id: 'heading', status: 'passed', evidence: [frame(0), frame(29)] }], audioUses: [] };
    await rt.fs.writeFile('/work/project/replication.review.json', JSON.stringify(review));
    await rt.fs.writeFile('/work/project/replication.plan.json', JSON.stringify({ version: 1, visual: { ...c.visual, evidence: [] }, events: [{ id: 'heading', segment: filled.project!.segments[0]!.id, span: [0, 30], mechanism: 'characters', method: 'deterministic typing', evidence: [] }] }));
    const cli = () => runCli(rt, ['video', 'replication', 'check', '/work/project', '--artifact', '/work/project/final.mp4']);
    expect((await cli()).code).toBe(0); expect(rt.json()).toMatchObject({ artifactReady: true, requirementsMet: true, qualityStatus: 'accepted' });
    review.events[0]!.evidence = [frame(60), frame(61)];
    await rt.fs.writeFile('/work/project/replication.review.json', JSON.stringify(review));
    expect((await cli()).code).toBe(2); expect(JSON.stringify(rt.json())).toContain('outside the actual final file');
    review.events[0]!.evidence = [frame(0), frame(29)];
    await rt.fs.writeFile('/work/project/replication.review.json', JSON.stringify(review));
    await rt.fs.writeFile('/work/project/final.mp4', 'changed artifact after its review');
    expect((await cli()).code).toBe(2); expect(rt.json()).toMatchObject({ artifactReady: true, requirementsMet: false, qualityStatus: 'needs_iteration' });
  });
});
