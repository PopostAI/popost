const DICT: Readonly<Record<Lang, Readonly<Record<Key, string>>>> = { en: EN, zh: ZH };

/** The interface language from the browser's: Chinese for any zh-*, English otherwise. */
export const defaultLang = (language: string | undefined): Lang => (language?.toLowerCase().startsWith('zh') ? 'zh' : 'en');

export const t = (lang: Lang, key: Key): string => DICT[lang][key];

export const isKey = (s: string): s is Key => Object.hasOwn(EN, s);

/** A label for a score dimension, or the name itself when the dictionary does not know it. */
export const dimensionLabel = (lang: Lang, name: string): string => (name in EN ? t(lang, name as Key) : name);
